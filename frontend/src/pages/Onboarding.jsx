import React, { useState } from 'react';
import { 
  Sparkles, 
  Target, 
  BookOpen, 
  CheckCircle2, 
  ArrowRight, 
  Bot, 
  Plus, 
  X,
  Zap,
  ShieldCheck
} from 'lucide-react';
import { useApp } from '../context/AppContext';

export default function Onboarding() {
  const { setActiveTab, refreshData, triggerToast } = useApp();

  const [name, setName] = useState('');
  const [currentSkills, setCurrentSkills] = useState(['Python', 'SQL', 'HTML']);
  const [newSkillInput, setNewSkillInput] = useState('');
  const [certifications, setCertifications] = useState('');
  const [projects, setProjects] = useState('');
  const [targetCareer, setTargetCareer] = useState('Full Stack Developer');
  const [loading, setLoading] = useState(false);
  const [agentStep, setAgentStep] = useState('');

  const careerOptions = [
    'Full Stack Developer',
    'AI Engineer',
    'Data Scientist',
    'Cybersecurity Analyst',
    'Cloud Architect',
  ];

  const suggestedSkills = [
    'Python', 'SQL', 'HTML', 'CSS', 'JavaScript', 'React', 'Node.js', 
    'Git', 'Docker', 'AWS', 'Linux', 'MongoDB', 'Java', 'C++', 'TypeScript'
  ];

  const toggleSuggestedSkill = (skill) => {
    if (currentSkills.includes(skill)) {
      setCurrentSkills(currentSkills.filter(s => s !== skill));
    } else {
      setCurrentSkills([...currentSkills, skill]);
    }
  };

  const addCustomSkill = () => {
    if (newSkillInput.trim() && !currentSkills.includes(newSkillInput.trim())) {
      setCurrentSkills([...currentSkills, newSkillInput.trim()]);
      setNewSkillInput('');
    }
  };

  const removeSkill = (skill) => {
    setCurrentSkills(currentSkills.filter(s => s !== skill));
  };

  const loadPromptWarsScenario = () => {
    setName('Lingesh');
    setCurrentSkills(['Python', 'SQL', 'HTML']);
    setCertifications('Meta Frontend Specialist, AWS Cloud Practitioner');
    setProjects('SQLite Inventory Tracker, Responsive HTML Portfolio');
    setTargetCareer('Full Stack Developer');
    triggerToast('Loaded PromptWars X RTC Scenario (Lingesh: Full Stack Dev)!', 'info');
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!name.trim()) {
      triggerToast('Please provide your name', 'warning');
      return;
    }
    if (currentSkills.length === 0) {
      triggerToast('Please select at least 1 current skill', 'warning');
      return;
    }

    setLoading(true);
    setAgentStep('Invoking Agent 1: Skill Analyzer Agent...');

    try {
      setTimeout(() => setAgentStep('Invoking Agent 2: Career Matcher Agent...'), 1200);
      setTimeout(() => setAgentStep('Invoking Agent 3: Learning Curator Agent...'), 2400);

      const res = await fetch('/api/onboarding', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          name,
          currentSkills,
          certifications,
          projects,
          targetCareer,
        }),
      });

      if (res.ok) {
        await refreshData();
        triggerToast('Profile saved and roadmap generated by Agent Swarm!', 'success');
        setActiveTab('dashboard');
      }
    } catch (err) {
      console.error('Error during onboarding:', err);
      triggerToast('Failed to complete onboarding', 'error');
    } finally {
      setLoading(false);
      setAgentStep('');
    }
  };

  return (
    <div className="max-w-3xl mx-auto space-y-6 animate-in fade-in duration-200">
      
      {/* Header Banner */}
      <div className="bg-white rounded-2xl p-6 sm:p-8 border border-slate-200 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <span className="px-2.5 py-0.5 rounded-md text-xs font-bold bg-indigo-50 text-indigo-700">
            Feature 1: User Profile Setup
          </span>
          <h1 className="text-2xl font-extrabold text-slate-900 mt-2">
            SkillPath AI Onboarding
          </h1>
          <p className="text-xs text-slate-500 mt-1">
            Provide your existing skills and career goal to trigger the collaborative AI Agent Swarm.
          </p>
        </div>

        {/* 1-Click PromptWars Demo Button */}
        <button
          type="button"
          onClick={loadPromptWarsScenario}
          className="flex items-center gap-2 px-4 py-2.5 rounded-xl bg-slate-900 hover:bg-slate-800 text-white text-xs font-bold shadow-xs transition-all shrink-0"
        >
          <Zap className="w-4 h-4 text-amber-400" />
          <span>Autofill PromptWars Scenario</span>
        </button>
      </div>

      {/* Clean Form Card */}
      <form onSubmit={handleSubmit} className="bg-white rounded-2xl p-6 sm:p-8 border border-slate-200 shadow-xs space-y-6">
        
        {/* Full Name */}
        <div>
          <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Learner Name
          </label>
          <input
            type="text"
            value={name}
            onChange={(e) => setName(e.target.value)}
            placeholder="e.g. Lingesh"
            className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
            required
          />
        </div>

        {/* Target Career Dropdown */}
        <div>
          <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Target Career Goal (Dropdown)
          </label>
          <select
            value={targetCareer}
            onChange={(e) => setTargetCareer(e.target.value)}
            className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 font-semibold text-slate-800"
          >
            {careerOptions.map((opt) => (
              <option key={opt} value={opt}>
                {opt}
              </option>
            ))}
          </select>
        </div>

        {/* Current Skills Multi-Select Tags */}
        <div>
          <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Current Skills (Multi-Select Tags)
          </label>

          <div className="flex flex-wrap gap-2 p-3 bg-slate-50 border border-slate-200 rounded-xl min-h-[50px] mb-3">
            {currentSkills.length === 0 ? (
              <span className="text-xs text-slate-400">Click suggestions below or type custom skills...</span>
            ) : (
              currentSkills.map((skill) => (
                <span
                  key={skill}
                  className="px-3 py-1 bg-indigo-600 text-white rounded-lg text-xs font-semibold flex items-center gap-1.5 shadow-2xs"
                >
                  <span>{skill}</span>
                  <button
                    type="button"
                    onClick={() => removeSkill(skill)}
                    className="hover:text-indigo-200 font-bold"
                  >
                    ×
                  </button>
                </span>
              ))
            )}
          </div>

          {/* Quick Custom Input */}
          <div className="flex items-center gap-2 mb-3">
            <input
              type="text"
              value={newSkillInput}
              onChange={(e) => setNewSkillInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter') {
                  e.preventDefault();
                  addCustomSkill();
                }
              }}
              placeholder="Add other skill (e.g. Tailwind, Docker)..."
              className="flex-1 px-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs focus:outline-none focus:border-indigo-500"
            />
            <button
              type="button"
              onClick={addCustomSkill}
              className="px-3 py-2 bg-indigo-50 text-indigo-700 hover:bg-indigo-100 rounded-lg text-xs font-bold"
            >
              + Add
            </button>
          </div>

          {/* Suggested Clickable Tags */}
          <div className="flex flex-wrap gap-1.5">
            {suggestedSkills.map((skill) => {
              const isSelected = currentSkills.includes(skill);
              return (
                <button
                  type="button"
                  key={skill}
                  onClick={() => toggleSuggestedSkill(skill)}
                  className={`px-2.5 py-1 rounded-md text-xs font-medium transition-all ${
                    isSelected
                      ? 'bg-indigo-600 text-white'
                      : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                  }`}
                >
                  {isSelected ? `✓ ${skill}` : `+ ${skill}`}
                </button>
              );
            })}
          </div>
        </div>

        {/* Certifications */}
        <div>
          <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Certifications (Optional)
          </label>
          <input
            type="text"
            value={certifications}
            onChange={(e) => setCertifications(e.target.value)}
            placeholder="e.g. Meta Frontend Specialist, AWS Cloud Practitioner"
            className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
          />
        </div>

        {/* Projects Text */}
        <div>
          <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Projects &amp; Experience (Text)
          </label>
          <textarea
            rows={3}
            value={projects}
            onChange={(e) => setProjects(e.target.value)}
            placeholder="e.g. Built SQLite inventory tracker and responsive HTML portfolio..."
            className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
          />
        </div>

        {/* Submit */}
        <div className="pt-2">
          {loading ? (
            <div className="p-4 rounded-xl bg-indigo-50 border border-indigo-200 flex items-center gap-3 text-indigo-900 text-xs font-bold animate-pulse">
              <Bot className="w-5 h-5 text-indigo-600 animate-spin" />
              <span>{agentStep || 'Collaborative AI Agent Swarm Running...'}</span>
            </div>
          ) : (
            <button
              type="submit"
              className="w-full py-3.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-sm font-bold shadow-sm transition-all flex items-center justify-center gap-2"
            >
              <span>Save Profile &amp; Generate Roadmap</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          )}
        </div>

      </form>

    </div>
  );
}
